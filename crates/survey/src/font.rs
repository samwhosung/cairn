fn glyph(c: char) -> Glyph {
    let c = c.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .or_else(|| GLYPHS.iter().find(|(g, _)| *g == '?'))
        .map_or([0; HEIGHT], |(_, rows)| *rows)
}

pub(crate) fn draw(
    img: &mut RgbImage,
    (x, y): (u32, u32),
    text: &str,
    scale: u32,
    max_chars: usize,
    color: [u8; 3],
) {
    for (i, c) in text.chars().take(max_chars).enumerate() {
        let left = x + i as u32 * ADVANCE * scale;
        for (row, bits) in glyph(c).iter().enumerate() {
            for col in 0..WIDTH {
                if bits & (LEFT_BIT >> col) == 0 {
                    continue;
                }
                for dy in 0..scale {
                    for dx in 0..scale {
                        let (px, py) = (left + col * scale + dx, y + row as u32 * scale + dy);
                        if px < img.width() && py < img.height() {
                            img.put_pixel(px, py, Rgb(color));
                        }
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_fits_its_cell_and_is_its_own() {
        for (c, rows) in GLYPHS {
            assert!(rows.iter().all(|r| *r < LEFT_BIT << 1), "{c}");
        }
        let mut seen: Vec<Glyph> = GLYPHS.iter().map(|(_, r)| *r).collect();
        seen.sort_unstable();
        seen.dedup();
        assert_eq!(seen.len(), GLYPHS.len());
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(glyph('~'), glyph('?'));
    }

    #[test]
    fn text_is_drawn_where_asked_and_clipped() {
        let mut img = RgbImage::new(20, 10);
        draw(&mut img, (0, 0), "I", 1, 10, [255, 255, 255]);
        assert_eq!(img.get_pixel(2, 0).0, [255, 255, 255], "the I's top bar");
        assert_eq!(img.get_pixel(0, 3).0, [0, 0, 0]);
        draw(&mut img, (15, 5), "WW", 2, 10, [9, 9, 9]);
        let mut clipped = RgbImage::new(20, 10);
        draw(&mut clipped, (0, 0), "II", 1, 1, [255, 255, 255]);
        assert_eq!(
            clipped.get_pixel(ADVANCE + 2, 0).0,
            [0, 0, 0],
            "one glyph only"
        );
    }
}
